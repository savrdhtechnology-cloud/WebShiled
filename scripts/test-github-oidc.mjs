import assert from 'node:assert/strict';
import {generateKeyPairSync,createSign} from 'node:crypto';
import {verifyOidcToken,looksLikeJwt} from '../lib/monitoring/github-oidc.ts';
const {publicKey,privateKey}=generateKeyPairSync('rsa',{modulusLength:2048});
const jwk={...publicKey.export({format:'jwk'}),kid:'k1',alg:'RS256'};
const b64=o=>Buffer.from(JSON.stringify(o)).toString('base64url');
const now=Date.parse('2026-10-21T12:00:00Z');
const sign=(claims,key=privateKey,kid='k1')=>{const head=b64({alg:'RS256',kid,typ:'JWT'})+'.'+b64(claims);const s=createSign('RSA-SHA256');s.update(head);return head+'.'+s.sign(key).toString('base64url')};
const good={iss:'https://token.actions.githubusercontent.com',aud:'webshield-monitor',repository:'savrdhtechnology-cloud/WebShiled',ref:'refs/heads/main',exp:now/1000+300,iat:now/1000};
const opts={repositories:['savrdhtechnology-cloud/webshiled'],now};
assert.equal(verifyOidcToken(sign(good),[jwk],opts).repository,'savrdhtechnology-cloud/WebShiled');
assert.ok(looksLikeJwt(sign(good))&&!looksLikeJwt('abc'));
const bad=(claims,msg,key,kid)=>assert.throws(()=>verifyOidcToken(sign(claims,key,kid),[jwk],opts),new RegExp(msg));
bad({...good,repository:'attacker/fork'},'Repository');
bad({...good,ref:'refs/heads/evil'},'main branch');
bad({...good,aud:'other'},'audience');
bad({...good,iss:'https://evil.example'},'issuer');
bad({...good,exp:now/1000-120},'expired');
bad(good,'signature',generateKeyPairSync('rsa',{modulusLength:2048}).privateKey);
bad(good,'Unknown signing key',privateKey,'k2');
const forged=sign(good).split('.');forged[1]=b64({...good,repository:'savrdhtechnology-cloud/WebShiled',ref:'refs/heads/x'});
assert.throws(()=>verifyOidcToken(forged.join('.'),[jwk],opts),/signature/);
console.log('GitHub OIDC monitor authentication checks passed.');
